template <class T> constexpr void solid_harmonics(T x, T y, T z, T* S) {
    const T xx = x*x;
    const T yy = y*y;
    const T zz = z*z;
    const T r2 = xx + yy + zz;
    const T f5 = 5*zz - r2;
    S[0] = 1;
    S[1] = y;
    S[2] = z;
    S[3] = x;
    S[4] = x*y;
    S[5] = y*z;
    S[6] = 3*zz - r2;
    S[7] = x*z;
    S[8] = xx - yy;
    S[9] = y*(3*xx - yy);
    S[10] = x*y*z;
    S[11] = y*f5;
    S[12] = z*(5*zz - 3*r2);
    S[13] = x*f5;
    S[14] = z*(xx - yy);
    S[15] = x*(xx - 3*yy);
}
