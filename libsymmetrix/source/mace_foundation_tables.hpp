template <int C_, int L_max_, int CN_ = C_, bool gated_ = false> struct Shape : Tables<L_max_> {
    using T = Tables<L_max_>;
    static constexpr int C = C_;
    static constexpr int CN = CN_;
    static constexpr int L_max = L_max_;
    static constexpr int num_LM = (L_max_ + 1)*(L_max_ + 1);
    static constexpr bool gated = gated_;
    static constexpr int width(int l) { return l == 0 and gated ? 4*CN : CN; }
    static constexpr int num_e(int l) {
        int n = 0;
        for (int p = 0; p < T::num_paths; ++p) n += T::Phi1_l[p] == l;
        return n;
    }
    static constexpr int lme_offset(int l) { return l == 0 ? 0 : lme_offset(l - 1) + num_e(l - 1)*(2*l - 1); }
    static constexpr int num_lme = lme_offset(4);
};
template <class Sh> constexpr bool same_key(int a, int b) {
    return Sh::terms[a].path == Sh::terms[b].path and Sh::terms[a].lm1 == Sh::terms[b].lm1
           and Sh::terms[a].lm2 == Sh::terms[b].lm2;
}
template <class Sh> constexpr bool first_term(int q) {
    for (int r = 0; r < q; ++r) if (same_key<Sh>(r, q)) return false;
    return true;
}
template <class Sh> constexpr int next_term(int q) {
    for (int r = q + 1; r < Sh::num_terms; ++r) if (same_key<Sh>(q, r)) return r;
    return -1;
}

